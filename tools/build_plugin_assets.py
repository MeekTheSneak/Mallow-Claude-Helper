"""Packs Mallow's art into the Claude Code plugin (plugin/hooks/assets.ts).

The plugin draws its pane as one SVG, and an SVG pane is capped at 131,072
characters, so every picture is shrunk and palette-reduced here and stored as
base64. Sizes are chosen per kind so each character keeps its size relative to
the others, exactly as in the app.

Run from the Mallow folder after changing web/sprites:
    python tools/build_plugin_assets.py
"""
import base64
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SPRITES = ROOT / "web" / "sprites"
OUT = ROOT / "plugin" / "hooks" / "assets.ts"
META = json.loads((SPRITES / "sprites.json").read_text())

FURS = ("ginger", "cream", "cocoa", "smoke")
# name list per kind, and how many encoded pixels per sprites.json pixel
KINDS = {
    "mallow": (120 / META["m-idle"]["h"], [
        "m-idle", "m-blink", "m-wave", "m-cheer", "m-sleep", "m-eat", "m-worried", "m-alert", "m-dance",
        "m-stretch", "m-run1", "m-run2", "m-run3", "m-run4",
        "k-ready", "k-swing1", "k-swing2", "k-swing3", "k-swing4", "k-victory", "k-polish"]),
    "baby": (64 / META["b-ginger-idle"]["h"],
             [f"b-{f}-{p}" for f in FURS for p in ("idle", "run1", "run3", "sword", "wave")]),
    "dragon": (150 / META["d-battle1"]["h"], ["d-sleep", "d-dizzy", "d-battle1", "d-battle2", "d-battle3", "d-battle4"]),
    "wear": (0.42, ["h-party", "h-crown", "h-flowers", "h-bow", "h-beanie", "h-chef", "h-helmet",
                    "g-explorer", "g-hardhat", "g-cap", "g-guard", "g-knight", "g-goggles", "g-glasses",
                    "gs-explorer", "gs-hardhat", "gs-cap", "gs-guard", "gs-knight", "gs-goggles", "gs-glasses"]),
    "prop": (0.5, ["p-beetle", "p-slime", "p-seed", "p-bowl", "p-house", "p-bottle", "p-plant"]),
    "wheel": (210 / META["wheel"]["w"], ["wheel", "wheel-stand"]),
}
ROOM_SIZE = (560, 240)


def png_b64(im, colors=128):
    q = im.quantize(colors=colors, method=Image.Quantize.FASTOCTREE)
    buf = io.BytesIO()
    q.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def main():
    out = {}
    for kind, (f, names) in KINDS.items():
        for name in names:
            m = META[name]
            im = Image.open(SPRITES / f"{name}.png").convert("RGBA")
            w, h = max(1, round(im.width * f)), max(1, round(im.height * f))
            im = im.resize((w, h), Image.LANCZOS)
            entry = {"mime": "png", "d": png_b64(im), "w": w, "h": h, "facing": m.get("facing", "front"),
                     "headX": round(m.get("headX", m["w"] / 2) * f, 1), "headW": round(m.get("headW", m["w"]) * f, 1)}
            if "anchorX" in m:
                entry["anchorX"] = round(m["anchorX"] * f, 1)
            out[name] = entry
    for room in ("day", "night", "knight"):
        im = Image.open(SPRITES / f"room-{room}.jpg").convert("RGB").resize(ROOM_SIZE, Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=64, optimize=True, progressive=True)
        out[f"room-{room}"] = {"mime": "jpeg", "d": base64.b64encode(buf.getvalue()).decode(),
                               "w": ROOM_SIZE[0], "h": ROOM_SIZE[1], "facing": "front", "headX": 0, "headW": 0}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}" for k, v in out.items())
    OUT.write_text(
        "// Generated by tools/build_plugin_assets.py from web/sprites. Do not edit by hand.\n"
        "export type Sprite = { mime: 'png' | 'jpeg'; d: string; w: number; h: number; facing: string;"
        " headX: number; headW: number; anchorX?: number }\n\n"
        "export const SPR: Record<string, Sprite> = {\n" + body + ",\n}\n", encoding="utf-8")
    total = sum(len(v["d"]) for v in out.values())
    print(f"{len(out)} pictures, {total:,} characters of base64 -> {OUT}")


if __name__ == "__main__":
    main()
